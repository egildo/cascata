/**
 * v1.1 (010) US4 — **named types emit as named aliases.**
 *
 * Rows 22–28 of `contracts/emitted-type.md` §1, and its §3 rows 2–4
 * (alias names, collisions, and the rule that the emitter references no
 * global type). Written by hand from the contract before the printer.
 *
 * The row with a finding behind it is 23. Two *different* declarations of
 * one name — §7's narrowing chain — are **not** emitted as `A & B`: an
 * alias intersection can be `never` where the semantic intersection is a
 * perfectly ordinary type, and an open layer's index signature survives `&`
 * with a closed one's object type, so `&` neither preserves the numeric
 * rule nor closes a seal (research F-2). The intersected body is emitted
 * inline instead, with JSDoc naming both declarations, and a synthesized
 * alias is used only where the recursion re-enters the set — which is the
 * one case inlining cannot terminate on.
 */

import { describe, expect, it } from "vitest";
import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { parse } from "../../src/index.js";
import { createOrigin } from "../../src/model/span.js";
import type { Layer } from "../../src/merge/provenance.js";
import { accumulate } from "../../src/generate/accumulate.js";
import { generate } from "../../src/generate/emit.js";
import { compileInMemory, renderProblems } from "./generate-literal.js";

const REPO_ROOT = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const ENCODER = new TextEncoder();
const HEADER = "// Generated by Cascata — do not edit. Regenerate from the schema chain.\n\n";

function schemaLayer(location: string, rank: number, text: string): Layer {
  const origin = createOrigin(location, location);
  const parsed = parse(ENCODER.encode(text), { origin });
  if (!parsed.ok) {
    throw new Error(`fixture '${location}' does not parse: ${parsed.diagnostics.map((d) => d.message).join("; ")}`);
  }
  return { identity: { location, hash: String(rank).repeat(64).slice(0, 64) }, role: "schema", rank, tree: parsed.tree };
}

function layersOf(texts: readonly string[]): readonly Layer[] {
  return texts.map((text, index) => schemaLayer(`layer${index}.yaml`, index, text));
}

function run(...texts: readonly string[]): { readonly source: string; readonly codes: readonly string[] } {
  const result = generate(accumulate(layersOf(texts)).tree);
  return { source: result.source, codes: result.diagnostics.map((d) => d.code) };
}

function emitAndCompile(...texts: readonly string[]): string {
  const { source } = run(...texts);
  const problems = compileInMemory(source);
  expect(problems, `the emitted module does not compile:\n${renderProblems(problems)}\n---\n${source}`).toEqual([]);
  return source;
}

/** Every `export type <name>` in emission order. */
function aliasNames(source: string): readonly string[] {
  return [...source.matchAll(/^export type (\S+) =/gm)].flatMap((match) => (match[1] === undefined ? [] : [match[1]]));
}

// --- rows 22, 24, 26: one declaration --------------------------------------

describe("contract rows 22, 24, 26 — a name the chain declares once keeps its bare name", () => {
  it("one declaration is one alias, and the usage points at it by name", () => {
    const source = emitAndCompile(`$id: vendor/core
types:
  resource:
    demand: { type: string }
keys:
  a: { demand: { type: resource } }
`);
    expect(source).toBe(`${HEADER}export type resource = string;

export type core = {
  readonly a?: resource;
  readonly [key: string]: unknown;
};
`);
  });

  it("row 26 — a guarded recursive declaration is a self-referencing alias TypeScript accepts", () => {
    const source = emitAndCompile(`$id: vendor/core
types:
  node:
    demand:
      type: mapping
      seal: closed
      keys: { child: { demand: { type: node } } }
keys:
  root: { demand: { type: node } }
`);
    expect(source).toContain("export type node = {\n  readonly child?: node;\n};");
  });

  it("row 28 — the root alias is named from the leaf's `$id` qualifier, and the option wins over it", () => {
    expect(aliasNames(emitAndCompile(`$id: site-builder/core\n`))).toEqual(["core"]);
    expect(aliasNames(emitAndCompile(`$version: 1\n`))).toEqual(["Configuration"]);
    const named = generate(accumulate(layersOf([`$id: site-builder/core\n`]), { rootName: "SiteConfig" }).tree).source;
    expect(aliasNames(named)).toEqual(["SiteConfig"]);
  });
});

// --- rows 23, 25: several declarations of one name -------------------------

const CORE_WITH_RESOURCE = `$id: vendor/core
types:
  resource:
    demand: { type: string }
keys:
  a: { demand: { type: resource } }
`;

describe("contract rows 23, 25 — a name declared by more than one layer", () => {
  it("every declaration is emitted, each carrying §7's qualifier; no declaration is privileged", () => {
    const source = emitAndCompile(
      CORE_WITH_RESOURCE,
      `$id: acme/house
types:
  resource:
    demand: { type: string, minLength: 1 }
keys:
  a: { demand: { type: resource } }
`,
    );
    expect(aliasNames(source)).toEqual(["core_resource", "house_resource", "house"]);
  });

  it("row 23 — a reference to both is the intersected body INLINE, with JSDoc naming each; never `A & B`", () => {
    const source = emitAndCompile(
      CORE_WITH_RESOURCE,
      `$id: acme/house
types:
  resource:
    demand: { type: string, minLength: 1 }
keys:
  a: { demand: { type: resource } }
`,
    );
    expect(source).toContain("@intersects core_resource, house_resource");
    expect(source).toContain("readonly a?: string;");
    expect(source).not.toContain("core_resource & house_resource");
  });

  it("and `&` really would have been unsound here — two bodies with distinct numeric classes intersect to `never`", () => {
    const joined = compileInMemory(`type A = number; type B = bigint; export const v: A & B = 1n;`);
    expect(joined.length).toBeGreaterThan(0);
    // The same chain, accumulated: root admits int|float, house narrows to
    // int, and the position is `bigint` — inhabited, where the alias
    // intersection is not.
    const source = emitAndCompile(
      `$id: vendor/core\ntypes:\n  n:\n    demand: { type: "int | float" }\nkeys:\n  a: { demand: { type: n } }\n`,
      `$id: acme/house\ntypes:\n  n:\n    demand: { type: int }\nkeys:\n  a: { demand: { type: n } }\n`,
    );
    expect(source).toContain("readonly a?: bigint;");
  });

  it("two declaring layers sharing a qualifier are distinguished by layer rank", () => {
    const source = emitAndCompile(
      `$id: shared/lib\ntypes:\n  t:\n    demand: { type: string }\nkeys:\n  a: { demand: { type: t } }\n`,
      `$id: shared/lib\ntypes:\n  t:\n    demand: { type: string }\nkeys:\n  a: { demand: { type: t } }\n`,
    );
    expect(aliasNames(source)).toEqual(["lib_0_t", "lib_1_t", "lib"]);
  });

  it("a recursion that re-enters a two-declaration set gets ONE synthesized alias, joined by `_and_`", () => {
    const text = `$id: vendor/core
types:
  node:
    demand:
      type: mapping
      seal: closed
      keys: { child: { demand: { type: node } } }
keys:
  root: { demand: { type: node } }
`;
    const source = emitAndCompile(text, text.replace("$id: vendor/core", "$id: acme/house"));
    expect(aliasNames(source)).toContain("core_node_and_house_node");
    expect(source).toContain("readonly root?: core_node_and_house_node;");
  });
});

// --- §3 rows 2–4: escapes, collisions, globals ------------------------------

describe("contract §3 rows 2–4 — alias names are kept, escaped, or refused", () => {
  it("a reserved word is escaped: `default` becomes `$default`", () => {
    const source = emitAndCompile(`types:\n  default:\n    demand: { type: string }\nkeys:\n  a: { demand: { type: 'default' } }\n`);
    expect(source).toContain("export type $default = string;");
    expect(source).toContain("readonly a?: $default;");
  });

  it("a hyphen is escaped: `my-type` becomes `$my_type`", () => {
    const source = emitAndCompile(`types:\n  my-type:\n    demand: { type: string }\nkeys:\n  a: { demand: { type: my-type } }\n`);
    expect(source).toContain("export type $my_type = string;");
  });

  it("row 3 — two names escaping to one identifier are an ERROR, and no source is emitted", () => {
    // **The contract's own §6 row names the wrong pair.** It says `a-b` and
    // `a_b` collide; they do not. `a_b` is already a bare ASCII identifier,
    // so it is never escaped, and `a-b` escapes to `$a_b` — and `$` cannot
    // begin a §9.1 identifier, which is precisely why the escape uses it. A
    // real collision needs **two escaped names**, so this pair is `a-b` and
    // `a b`: the second is declarable as a `types:` key (`typeName` is
    // deliberately unpatterned in the meta-schema) and both reach `$a_b`.
    // Reported as a defect in contracts/emitted-type.md §6 and in research
    // D-6, whose own sentence contradicts itself on this point.
    const result = run(`types:\n  a-b:\n    demand: { type: string }\n  ? a b\n  : demand: { type: int }\n`);
    expect(result.codes).toEqual(["emit-identifier-collision"]);
    expect(result.source).toBe("");
  });

  it("`a-b` and `a_b` do NOT collide — a bare name and an escaped one never can, because `$` cannot start a §9.1 identifier", () => {
    const result = run(`types:\n  a-b:\n    demand: { type: string }\n  a_b:\n    demand: { type: int }\n`);
    expect(result.codes).toEqual([]);
    expect(aliasNames(result.source)).toEqual(["$a_b", "a_b", "Configuration"]);
  });

  it("row 4 / research F-5 — a type named `Object` is emitted bare and shadows harmlessly", () => {
    const source = emitAndCompile(`types:\n  Object:\n    demand: { type: string }\nkeys:\n  a: { demand: { type: Object } }\n`);
    expect(source).toContain("export type Object = string;");
    expect(source).toContain("readonly a?: Object;");
  });

  it("and the emitter references no global type name anywhere, which is what makes that shadow safe", () => {
    const emitter = readFileSync(join(REPO_ROOT, "src", "generate", "emit.ts"), "utf-8");
    for (const global of ["Readonly<", "Record<", "Array<", "Object<", "Partial<"]) {
      expect(emitter.includes(global), `emit.ts writes '${global}' — a schema type of that name would then shadow something the emitted text relies on`).toBe(false);
    }
  });
});

// --- row 27: accept ---------------------------------------------------------

describe("contract row 27 — `accept` narrows where alternatives differ, and reaches JSDoc where they do not", () => {
  it("§7's own `resource`, narrowed from `[url, path]` to `[url]`, still emits `string`", () => {
    const source = emitAndCompile(`$id: site-builder/core
types:
  resource:
    accept: [url, path]
    demand: { type: string }
keys:
  styles:
    demand: { type: "resource[]", accept: [url] }
`);
    expect(source).toContain("readonly styles?: readonly string[];");
    expect(source).toContain("@demand accept: url");
  });

  it("where the alternatives DO have distinct emissions, the narrowed union is what is emitted", () => {
    const source = emitAndCompile(`types:
  either:
    accept: [int, string]
    demand: { type: "int | string" }
keys:
  a: { demand: { type: either, accept: [string] } }
`);
    expect(source).toContain("readonly a?: string;");
  });
});

// --- the meta-schema --------------------------------------------------------

describe("US4's independent test — the meta-schema's six named types", () => {
  const META = readFileSync(join(REPO_ROOT, "meta", "cascata.meta.yaml"), "utf-8");

  it("emits six aliases plus the root, all bare, and the module compiles", () => {
    const source = emitAndCompile(META);
    expect(aliasNames(source)).toEqual(["demand", "keyDecl", "nestedKeyDecl", "typeDecl", "typeExpr", "typeName", "meta"]);
  });

  it("`demand` is a recursive alias TypeScript accepts, reaching itself through `items` and `values`", () => {
    const source = emitAndCompile(META);
    const body = /^export type demand = ([\s\S]*?^};)$/m.exec(source)?.[1] ?? "";
    expect(body).toContain("readonly items?: demand;");
    expect(body).toContain("readonly values?: demand;");
    expect(body).toContain("readonly keys?: {\n    readonly [key: string]: nestedKeyDecl;\n  };");
  });

  it("`nestedKeyDecl` reaches back to `demand` — the mutual recursion the bootstrap needed §7's amendment for", () => {
    const source = emitAndCompile(META);
    // Properties come out in §4.2's code-point order, so `delegate`
    // precedes `demand` ('l' < 'm').
    expect(source).toContain("export type nestedKeyDecl = {\n  readonly delegate?: \"allow\";\n  readonly demand?: demand;\n};");
  });

  it("the meta-schema's own top level is closed, so the root carries no index signature", () => {
    const source = emitAndCompile(META);
    const root = /^export type meta = ([\s\S]*?^};)$/m.exec(source)?.[1] ?? "";
    // Nested positions inside the root (`types`, `keys`) are open mappings
    // of author-chosen names and DO carry index signatures; what must be
    // absent is one at the root's own level, which is indent 2.
    expect(root).not.toMatch(/^ {2}readonly \[key: string\]/m);
    expect(root).toContain("readonly types?:");
  });
});
