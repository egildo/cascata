/**
 * v1.1 (010) US2 — **shapes emit as object types.**
 *
 * Rows 6 through 17 of `specs/010-type-generator/contracts/emitted-type.md`
 * §1, its §3 row 1 (property names), and its §6 edge-case table. Every
 * expected text below is written by hand from those rows — the contract is
 * the specification and the emitter is what is on trial, so an expectation
 * read off the emitter's own output would be a tautology (Principle V).
 *
 * **Every expectation is also compiled.** A hand-written expected text that
 * is not valid TypeScript would otherwise sit in a string comparison
 * forever, green and wrong; `expectSource` runs each one through the same
 * in-memory compiler the soundness oracle uses.
 */

import { describe, expect, it } from "vitest";
import { parse } from "../../src/index.js";
import { createOrigin } from "../../src/model/span.js";
import type { Layer } from "../../src/merge/provenance.js";
import { accumulate } from "../../src/generate/accumulate.js";
import { generate } from "../../src/generate/emit.js";
import { compileInMemory, renderProblems } from "./generate-literal.js";

const ENCODER = new TextEncoder();

function schemaLayer(location: string, rank: number, text: string, maxDepth?: number): Layer {
  const origin = createOrigin(location, location);
  const parsed = parse(ENCODER.encode(text), { origin, ...(maxDepth !== undefined ? { limits: { maxDepth } } : {}) });
  if (!parsed.ok) {
    throw new Error(`fixture '${location}' does not parse: ${parsed.diagnostics.map((d) => d.message).join("; ")}`);
  }
  return { identity: { location, physical: location, hash: String(rank).repeat(64).slice(0, 64) }, role: "schema", rank, tree: parsed.tree };
}

function emit(...texts: readonly string[]): string {
  const layers = texts.map((text, index) => schemaLayer(`layer${index}.yaml`, index, text));
  const accumulated = accumulate(layers);
  return generate(accumulated.tree).source;
}

/** As `emit`, with the parser's own depth cap raised — a 64-level *demand* nest is three YAML levels per demand level and cannot be written under §11's default. */
function emitDeep(text: string, maxDepth: number): string {
  return generate(accumulate([schemaLayer("deep.yaml", 0, text, maxDepth)]).tree).source;
}

/** The emitted text equals the hand-written expectation **and** compiles. */
function expectSource(actual: string, expected: string): void {
  expect(actual).toBe(expected);
  const problems = compileInMemory(actual);
  expect(problems, `the expected text does not compile:\n${renderProblems(problems)}`).toEqual([]);
}

const HEADER = "// Generated by Cascata — do not edit. Regenerate from the schema chain.\n\n";

/** A module whose only declaration is the root alias. */
function rootModule(body: string): string {
  return `${HEADER}export type Configuration = ${body};\n`;
}

// --- rows 8, 9: keys and optionality --------------------------------------

describe("contract rows 8–9 — `keys` emits an object type; `required` or `provided` makes a property non-optional", () => {
  it("US2's independent test: a required key, a provided key, and a plain key", () => {
    const source = emit(`keys:
  needed:
    demand: { type: string, required: true }
  given:
    provide: "x"
    demand: { type: string }
  plain:
    demand: { type: string }
`);
    expectSource(
      source,
      rootModule(`{
  readonly given: string;
  readonly needed: string;
  readonly plain?: string;
  readonly [key: string]: unknown;
}`),
    );
  });

  it("properties come out in §4.2's code-point order, not the document's", () => {
    const source = emit(`keys:
  zulu: { demand: { type: string } }
  alpha: { demand: { type: string } }
  Mike: { demand: { type: string } }
`);
    expectSource(
      source,
      rootModule(`{
  readonly Mike?: string;
  readonly alpha?: string;
  readonly zulu?: string;
  readonly [key: string]: unknown;
}`),
    );
  });

  it("`required` in ANY layer is enough — optionality is the accumulated demand's, not the leaf's", () => {
    const source = emit(`keys:\n  a: { demand: { type: string, required: true } }\n`, `keys:\n  a: { demand: { type: string } }\n`);
    expectSource(
      source,
      rootModule(`{
  readonly a: string;
  readonly [key: string]: unknown;
}`),
    );
  });
});

// --- rows 6, 7: arrays -----------------------------------------------------

describe("contract rows 6–7 — arrays are `readonly`, and nest", () => {
  it("`items: D` emits `readonly D[]`", () => {
    const source = emit(`keys:\n  s: { demand: { type: sequence, items: { type: string } } }\n`);
    expectSource(
      source,
      rootModule(`{
  readonly s?: readonly string[];
  readonly [key: string]: unknown;
}`),
    );
  });

  it("depth 2 nests: `readonly (readonly string[])[]`", () => {
    const source = emit(`keys:\n  s: { demand: { type: "string[][]" } }\n`);
    expectSource(
      source,
      rootModule(`{
  readonly s?: readonly (readonly string[])[];
  readonly [key: string]: unknown;
}`),
    );
  });

  it("a union inside an array is parenthesized (row 5's precedence)", () => {
    const source = emit(`keys:\n  s: { demand: { type: sequence, items: { type: "string | bool" } } }\n`);
    expectSource(
      source,
      rootModule(`{
  readonly s?: readonly (boolean | string)[];
  readonly [key: string]: unknown;
}`),
    );
  });

  it("a `sequence` with no `items` says only that it is a sequence", () => {
    const source = emit(`keys:\n  s: { demand: { type: sequence } }\n`);
    expectSource(
      source,
      rootModule(`{
  readonly s?: readonly unknown[];
  readonly [key: string]: unknown;
}`),
    );
  });
});

// --- rows 10–14: the index signature and the seal --------------------------

describe("contract rows 10–14 — `values`, `seal`, and the index signature", () => {
  it("row 10 — `values: D` emits `readonly [key: string]: D`", () => {
    const source = emit(`keys:\n  m: { demand: { type: mapping, values: { type: string } } }\n`);
    expectSource(
      source,
      rootModule(`{
  readonly m?: {
    readonly [key: string]: string;
  };
  readonly [key: string]: unknown;
}`),
    );
  });

  it("row 11 — a key named by `keys` AND covered by `values` carries the intersection, not `T & D`", () => {
    // **The `| undefined` is a correction the compiler forced, not a
    // decoration.** Row 10 promises `readonly [key: string]: D` and row 9
    // makes an undemanded key optional; the two cannot both hold, because
    // TypeScript requires an index signature to subsume every declared
    // property's type and an optional `k?: string` has type `string |
    // undefined` (TS2411: "Property 'k' of type 'string | undefined' is not
    // assignable to 'string' index type 'string'"). It is also the more
    // honest type — an arbitrary key of an open mapping may not be there at
    // all. Reported as a correction owed to contract row 10 and FR-018.
    const source = emit(`keys:
  m:
    demand:
      type: mapping
      keys: { k: { demand: { type: "string | bool" } } }
      values: { type: string }
`);
    expectSource(
      source,
      rootModule(`{
  readonly m?: {
    readonly k?: string;
    readonly [key: string]: string | undefined;
  };
  readonly [key: string]: unknown;
}`),
    );
  });

  it("and row 10's plain `D` still holds where the mapping declares no keys of its own", () => {
    expectSource(
      emit(`keys:\n  m: { demand: { type: mapping, values: { type: string } } }\n`),
      rootModule(`{
  readonly m?: {
    readonly [key: string]: string;
  };
  readonly [key: string]: unknown;
}`),
    );
  });

  it("row 12 — `seal: open` with no `values` emits an index signature of `unknown`", () => {
    const source = emit(`keys:\n  m: { demand: { type: mapping, keys: { a: { demand: { type: string } } } } }\n`);
    expectSource(
      source,
      rootModule(`{
  readonly m?: {
    readonly a?: string;
    readonly [key: string]: unknown;
  };
  readonly [key: string]: unknown;
}`),
    );
  });

  it("row 13 — `seal: closed` with keys declared emits NO index signature", () => {
    const source = emit(`keys:\n  m: { demand: { type: mapping, seal: closed, keys: { a: { demand: { type: string } } } } }\n`);
    expectSource(
      source,
      rootModule(`{
  readonly m?: {
    readonly a?: string;
  };
  readonly [key: string]: unknown;
}`),
    );
  });

  it("row 14 — `seal: closed` with NO keys is `{ readonly [key: string]: never }`, never `{}`", () => {
    const source = emit(`keys:\n  m: { demand: { type: mapping, seal: closed } }\n`);
    expectSource(
      source,
      rootModule(`{
  readonly m?: {
    readonly [key: string]: never;
  };
  readonly [key: string]: unknown;
}`),
    );
  });

  it("and `{}` would have been wrong: it admits every non-nullish value, `never` admits nothing (research F-4)", () => {
    const closedEmpty = compileInMemory(`type T = { readonly [key: string]: never }; export const v: T = { a: 1 };`);
    const braces = compileInMemory(`type T = {}; export const v: T = { a: 1 };`);
    expect(closedEmpty.length, "the emitted form must refuse an extra key").toBeGreaterThan(0);
    expect(braces.length, "`{}` would have accepted it — which is why the contract's row 14 is a correction").toBe(0);
  });

  it("row 14 at the ROOT — a schema sealing its own top level with no keys admits nothing", () => {
    expectSource(
      emit(`seal: closed\n`),
      rootModule(`{
  readonly [key: string]: never;
}`),
    );
  });
});

// --- rows 15–17: undemanded positions --------------------------------------

describe("contract rows 15–17 — what an undemanded position emits", () => {
  it("row 15 — a demanded key with no `type` is `unknown`", () => {
    expectSource(
      emit(`keys:\n  a: { demand: { required: true } }\n`),
      rootModule(`{
  readonly a: unknown;
  readonly [key: string]: unknown;
}`),
    );
  });

  it("row 16 — a provided but undemanded key is a NON-optional `unknown`", () => {
    expectSource(
      emit(`keys:\n  k: { provide: "x" }\n`),
      rootModule(`{
  readonly k: unknown;
  readonly [key: string]: unknown;
}`),
    );
  });

  it("row 17 — a key neither demanded nor provided is not a property at all; the index signature covers it", () => {
    expectSource(
      emit(`keys:\n  k: { cascade: append }\n`),
      rootModule(`{
  readonly [key: string]: unknown;
}`),
    );
  });

  it("a schema declaring nothing at all still emits a root", () => {
    expectSource(
      emit(`$version: 1\n`),
      rootModule(`{
  readonly [key: string]: unknown;
}`),
    );
  });
});

// --- §3 row 1 / §6: property names -----------------------------------------

describe("contract §3 row 1 / §6 — a key is kept bare or quoted verbatim, never renamed", () => {
  it("every key outside `[A-Za-z_$][A-Za-z0-9_$]*` is a quoted property name", () => {
    const source = emit(`keys:
  my-key: { demand: { type: string } }
  città: { demand: { type: string } }
  🍝: { demand: { type: string } }
  "10": { demand: { type: string } }
  __proto__: { demand: { type: string } }
  constructor: { demand: { type: string } }
  plain$name_9: { demand: { type: string } }
`);
    // Code-point order: "10" (U+0031), "__proto__" (U+005F), "città"
    // (c,i…) before "constructor" (c,o…), then "my-key", "plain$name_9",
    // and the emoji last at U+1F35D.
    expectSource(
      source,
      rootModule(`{
  readonly "10"?: string;
  readonly __proto__?: string;
  readonly "città"?: string;
  readonly constructor?: string;
  readonly "my-key"?: string;
  readonly plain$name_9?: string;
  readonly "🍝"?: string;
  readonly [key: string]: unknown;
}`),
    );
  });

  it("a quoted `__proto__` property accepts an object literal that sets it — which is the whole point of §17's null prototype", () => {
    const problems = compileInMemory(`export type T = { readonly "__proto__": string };
export const v: T = { "__proto__": "ordinary own property" };
`);
    expect(problems, renderProblems(problems)).toEqual([]);
  });
});

// --- §6: the remaining edge cases ------------------------------------------

describe("contract §6 — the edge-case table", () => {
  it("`keys: {}` open is an index signature of `unknown`; closed is `never`", () => {
    expectSource(
      emit(`keys:\n  m: { demand: { type: mapping, keys: {} } }\n`),
      rootModule(`{
  readonly m?: {
    readonly [key: string]: unknown;
  };
  readonly [key: string]: unknown;
}`),
    );
    expectSource(
      emit(`keys:\n  m: { demand: { type: mapping, keys: {}, seal: closed } }\n`),
      rootModule(`{
  readonly m?: {
    readonly [key: string]: never;
  };
  readonly [key: string]: unknown;
}`),
    );
  });

  it("`values` whose demand is itself `values` nests one index signature inside another", () => {
    expectSource(
      emit(`keys:\n  m:\n    demand:\n      type: mapping\n      values: { type: mapping, values: { type: string } }\n`),
      rootModule(`{
  readonly m?: {
    readonly [key: string]: {
      readonly [key: string]: string;
    };
  };
  readonly [key: string]: unknown;
}`),
    );
  });

  it("a schema's top-level `seal: closed` suppresses the ROOT's index signature (FR-014)", () => {
    expectSource(
      emit(`seal: closed\nkeys:\n  a: { demand: { type: string, required: true } }\n`),
      rootModule(`{
  readonly a: string;
}`),
    );
  });

  it("a 64-deep `keys` nest emits 64 nested object types, and they typecheck", () => {
    const lines: string[] = ["seal: closed", "keys:"];
    let indent = "  ";
    for (let level = 0; level < 63; level += 1) {
      lines.push(`${indent}k${level}:`);
      lines.push(`${indent}  demand:`);
      lines.push(`${indent}    type: mapping`);
      lines.push(`${indent}    seal: closed`);
      lines.push(`${indent}    keys:`);
      indent += "      ";
    }
    lines.push(`${indent}leaf: { demand: { type: string } }`);
    // §11's own 64-level *document* cap is not the demand cap: each demand
    // level costs three YAML levels (`kN:` → `demand:` → `keys:`). The
    // parser's limit is raised for this one fixture so the demand nest —
    // which `MAX_DEMAND_DEPTH` caps at 64 — can actually be written.
    const source = emitDeep(`${lines.join("\n")}\n`, 512);
    expect((source.match(/readonly k\d+\?: \{/g) ?? []).length).toBe(63);
    expect(source).toContain("readonly leaf?: string;");
    const problems = compileInMemory(source);
    expect(problems, renderProblems(problems)).toEqual([]);
  });
});
